import fs from 'node:fs';
// Standard PDFium Courier-compatible CFF fonts shipped by existing pdfjs-dist.
// Vendored as text so Cloudflare needs neither a filesystem nor a font download.
const fonts=['FoxitFixed','FoxitFixedBold'];
const sources=fonts.map(name=>{
  const bytes=fs.readFileSync(`node_modules/pdfjs-dist/standard_fonts/${name}.pfb`);
  if(bytes[0]!==1||bytes[1]!==0)throw new Error('Expected CFF font data');
  return `export const ${name} = '${bytes.toString('hex')}';\n`;
});
const license=fs.readFileSync('node_modules/pdfjs-dist/standard_fonts/LICENSE_FOXIT','utf8');
fs.writeFileSync('lib/exercises/pdf-fonts.ts',license+'\n// Generated by scripts/vendor-exercise-pdf-fonts.mjs; PDFium Courier-compatible CFF.\n'+sources.join(''));
